def f_qcd_photon(T_K):
    """Photon frequency of a temperature [Hz]: nu = k_B*T/h."""
    return k_B * T_K / h


def kretschmann_horizon(M_kg):
    """Kretschmann scalar K = 3 c^8 / (4 G^4 M^4) at the Schwarzschild horizon [1/m^4]."""
    return 3.0 * c**8 / (4.0 * G**4 * M_kg**4)


def rho_mean(M_kg):
    """Mean density inside the Schwarzschild horizon rho = 3M/(4 pi r_s^3) [kg/m^3]."""
    r_s = 2.0 * G * M_kg / c**2
    return 3.0 * M_kg / (4.0 * math.pi * r_s**3)
