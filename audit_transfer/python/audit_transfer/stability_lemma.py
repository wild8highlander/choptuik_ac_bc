        Gh = (2 * np.trace(Ph @ Ph).real + 2 * np.trace(Qh @ Qh).real
              + 3 * np.trace(Ph @ Qh).real - 4 * n * (np.trace(P).real + np.trace(Q).real) / n
              + 3 * n)
