def part_2_sharpness():
    """(ii) Острота: конструкция 5n/7 + численная минимизация."""
    sub("3.2 (ii) ОСТРОТА: конструкция F = 5n/7 и численная минимизация")
    print("\n  Конструкция — СЛУЧАЙ РАВЕНСТВА острой теоремы (i): X₁ = X₂ = √(4/7)·I:")
    constr = {}
    for n in [1, 2, 3, 4, 5, 6, 8]:
        a = math.sqrt(4.0 / 7.0)
        F = leavitt_F(a * np.eye(n), a * np.eye(n))
        ok = abs(F - 5.0 * n / 7.0) < 1e-10
        constr[n] = {"F": float(F), "target": 5.0 * n / 7.0, "ok": bool(ok)}
        print(f"    n={n}: F = {F:.12f}, 5n/7 = {5.0 * n / 7.0:.12f}  "
              f"{'OK' if ok else 'FAIL'}")

    print("\n  n=1 аналитически (иллюстрация общего случая): sᵢ = |xᵢ|², F = (s₁−1)²+(s₂−1)²+s₁s₂+(s₁+s₂−1)²;")
    print("  стационар: 4s₁+3s₂ = 4, 3s₁+4s₂ = 4  ⇒  s₁ = s₂ = 4/7, F_min = 5/7.")

    print("\n  Численная минимизация (L-BFGS-B, 25 рестартов) — независимое подтверждение теоремы (i):")
    from scipy.optimize import minimize
    fmin = {}
    for n in [1, 2, 3, 4, 5, 6]:
        best = np.inf
        dim = 4 * n * n
        for r in range(25):
            rng = np.random.default_rng(5000 + 97 * r + n)
            p0 = rng.standard_normal(dim)

            def f(p):
                x1 = p[:2 * n * n].reshape(2, n, n)
                x2 = p[2 * n * n:].reshape(2, n, n)
                X1 = x1[0] + 1j * x1[1]
                X2 = x2[0] + 1j * x2[1]
                return leavitt_F(X1, X2)

            res = minimize(f, p0, method="L-BFGS-B",
                           options={"maxiter": 3000, "ftol": 1e-14,
                                    "gtol": 1e-12})
            best = min(best, res.fun)
        gap = best - 5.0 * n / 7.0
        fmin[n] = {"F_min": float(best), "5n_over_7": 5.0 * n / 7.0,
                   "gap": float(gap),
                   "per_dim": float(best / n)}
        print(f"    n={n}: F_min = {best:12.6f}  против 5n/7 = {5.0 * n / 7.0:12.6f}  "
              f"(зазор {gap:+.2e}; e = F/n = {best / n:.6f})")
    print("\n  ВЫВОД: острый пол дефекта на душу размерности e* = 5/7 ≈ 0.7143")
    print("  ДОКАЗАН аналитически для всех n (теорема (i), выпуклость+Хаар):")
    print("  НИКАКАЯ последовательность матричных моделей не даёт e → 0.")
    return {"construction": constr, "numerical_min": fmin,
            "per_dimension_floor": 5.0 / 7.0}


