def part_3_permutation_models():
    """Перестановочные модели с точными первыми соотношениями: F = 2n."""
    sub("3.3 Перестановочные модели: точные σᵢτᵢ = id ⇒ дефект F = 2n")
    print("  Пусть P₁,Q₁,P₂,Q₂ — матрицы подстановок, PᵢQᵢ = I точно (i = 1,2):")
    print("  тогда Qᵢ = Pᵢ⁻¹, Q₁P₁ = I ⇒ Q₂P₂ = 0 — НЕВОЗМОЖНО для подстановок;")
    print("  дефект: F = 0 + 0 + ‖P₁ᵀP₂‖² + ‖Q₁P₁+Q₂P₂−I‖² = n + n = 2n (ровно).")
    rng = np.random.default_rng(777)
    rows = {}
    for n in [3, 4, 5, 6, 8]:
        ok_all = True
        for _ in range(200):
            p1 = np.eye(n)[rng.permutation(n)]
            p2 = np.eye(n)[rng.permutation(n)]
            q1, q2 = p1.T, p2.T
            F = leavitt_F(p1.astype(float), p2.astype(float))
