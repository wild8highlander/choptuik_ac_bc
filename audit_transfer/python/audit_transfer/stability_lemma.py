def leavitt_F(x1, x2):
    """Кунцевский дефект F(X₁,X₂) (норма Фробениуса)."""
    I = np.eye(x1.shape[0])
    return (np.linalg.norm(x1.conj().T @ x1 - I, 'fro') ** 2
            + np.linalg.norm(x2.conj().T @ x2 - I, 'fro') ** 2
            + np.linalg.norm(x1.conj().T @ x2, 'fro') ** 2
            + np.linalg.norm(x1 @ x1.conj().T + x2 @ x2.conj().T - I, 'fro') ** 2)


