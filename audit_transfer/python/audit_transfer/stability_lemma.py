def part_4_contrast_f2():
    """Контраст: F₂ (размывание) vs пара Ливитта (пол 5/7)."""
    sub("3.4 Контраст механизмов: F₂ — размывание, Ливитт — пол 5/7")

    def reduced_words(max_len):
        W = []
        gens = ["a", "A", "b", "B"]

        def rec(w, last):
            if len(w) >= 1:
                W.append(w)
            if len(w) == max_len:
                return
            for g in gens:
                if w and ((g == "a" and last == "A") or (g == "A" and last == "a")
                          or (g == "b" and last == "B") or (g == "B" and last == "b")):
                    continue
                rec(w + g, g)
        rec("", "")
        return W

    sofic = {}
    print("  Софический профиль F₂ (случайные подстановки, слова ≤ 6):")
    print("   N   | min Hamming(w)/N | доля слов с Hamming/N < 0.05")
    for N in [50, 100, 200]:
        rng = np.random.default_rng(1000 + N)
        s, t = rng.permutation(N), rng.permutation(N)
        si, ti = np.argsort(s), np.argsort(t)
        W = reduced_words(6)
        worst, cnt = 1.0, 0
        for w in W:
            x = np.arange(N)
            m = {"a": s, "A": si, "b": t, "B": ti}
            for ch in w:
                x = m[ch][x]
            h = np.count_nonzero(x != np.arange(N)) / N
            worst = min(worst, h)
            cnt += (h < 0.05)
        sofic[N] = {"min_hamming": float(worst),
                    "frac_near_id": cnt / len(W)}
        print(f"   {N:4d} | {worst:.4f}           | {cnt}/{len(W)}")
    print("  → у F₂ слова уходят от единицы на ВЕСЬ диапазон: дефект размывается.")

    print("\n  Пара Ливитта: пол e = F/n ≥ 5/7 (острая теорема следа), достигается:")
    print("  e(n) = 5/7 при всех n — КОНСТАНТА, не убывает с масштабом.")
    print("  → «поправка, которая работает в бесконечность»: её нельзя размыть.")
    return {"sofic_F2": sofic,
            "leavitt_floor_per_dim": 5.0 / 7.0}


